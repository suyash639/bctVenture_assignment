"use client";

import Link from "next/link";
import { useMemo, useState } from "react";
import { useDashboardData } from "@/components/DataProvider";
import { Gate } from "@/components/Gate";
import { EmptyState, PageHeader, Tag } from "@/components/ui";
import { scopeKind } from "@/lib/filters";
import type { Insight } from "@/lib/types";

export default function InsightsPage() {
  const { loading, data } = useDashboardData();
  return (
    <>
      <PageHeader
        title="Intelligence & Insights"
        description="Observations generated by the analysis pipeline from measured features. Statements are shown verbatim with their sample size, method, caveats and the exact ads that support them. They describe the creatives; they make no claim about ad performance."
      />
      <Gate loading={loading} result={data?.insights} title="Insights not available">
        {(obs) => <InsightsBody obs={obs} />}
      </Gate>
    </>
  );
}

function InsightsBody({ obs }: { obs: Insight[] }) {
  const { adIndex } = useDashboardData();
  const [scope, setScope] = useState("all");
  const [status, setStatus] = useState("all");
  const kinds = useMemo(() => [...new Set(obs.map((o) => scopeKind(o.scope)))].sort(), [obs]);
  const statuses = useMemo(() => [...new Set(obs.map((o) => o.status))].sort(), [obs]);
  const shown = obs.filter((o) => (scope === "all" || scopeKind(o.scope) === scope) && (status === "all" || o.status === status));
  return (
    <>
      <div className="mb-4 flex flex-wrap items-end gap-3 rounded-lg border border-slate-200 bg-white p-3 shadow-sm">
        <label className="flex flex-col gap-1 text-xs font-medium text-slate-600" htmlFor="scope">
          Scope
          <select id="scope" value={scope} onChange={(e) => setScope(e.target.value)} className="rounded-md border border-slate-300 px-2 py-1.5 text-sm">
            <option value="all">All</option>
            {kinds.map((k) => <option key={k} value={k}>{k.replace(/_/g, " ")}</option>)}
          </select>
        </label>
        <label className="flex flex-col gap-1 text-xs font-medium text-slate-600" htmlFor="status">
          Status
          <select id="status" value={status} onChange={(e) => setStatus(e.target.value)} className="rounded-md border border-slate-300 px-2 py-1.5 text-sm">
            <option value="all">All</option>
            {statuses.map((k) => <option key={k} value={k}>{k.replace(/_/g, " ")}</option>)}
          </select>
        </label>
        <span aria-live="polite" className="ml-auto text-xs text-slate-500">{shown.length} of {obs.length} observations</span>
      </div>
      {shown.length === 0 ? (
        <EmptyState title="No observations match" />
      ) : (
        <ol className="space-y-3">
          {shown.map((o) => <ObservationCard key={o.observation_id} o={o} known={(id) => adIndex.has(id)} />)}
        </ol>
      )}
    </>
  );
}

function ObservationCard({ o, known }: { o: Insight; known: (id: string) => boolean }) {
  const [expanded, setExpanded] = useState(false);
  const ids = expanded ? o.supporting_ad_ids : o.supporting_ad_ids.slice(0, 12);
  return (
    <li id={o.observation_id} className="scroll-mt-6 rounded-lg border border-slate-200 bg-white p-4 shadow-sm">
      <div className="flex flex-wrap items-center gap-2 text-xs">
        <Tag tone="accent">{o.scope}</Tag>
        <Tag tone={o.status === "ok" ? "neutral" : "warn"}>{o.status.replace(/_/g, " ")}</Tag>
        <span className="text-slate-500">n = {o.n}</span>
        <span className="font-mono text-slate-400">{o.observation_id}</span>
      </div>
      <p className="mt-2 text-sm font-medium text-slate-900">{o.statement}</p>
      <dl className="mt-3 grid gap-x-4 gap-y-1 text-xs sm:grid-cols-2">
        <div><dt className="inline text-slate-500">Metric: </dt><dd className="inline text-slate-700">{o.metric}</dd></div>
        <div><dt className="inline text-slate-500">Value: </dt><dd className="inline break-words text-slate-700">{display(o.value)}</dd></div>
        <div><dt className="inline text-slate-500">Comparison: </dt><dd className="inline break-words text-slate-700">{display(o.comparison)}</dd></div>
        <div><dt className="inline text-slate-500">Method: </dt><dd className="inline text-slate-700">{o.method}</dd></div>
      </dl>
      {o.caveats.length ? (
        <ul className="mt-2 list-disc space-y-0.5 pl-5 text-xs text-amber-800">
          {o.caveats.map((c) => <li key={c}>{c}</li>)}
        </ul>
      ) : null}
      <div className="mt-3">
        <p className="text-xs text-slate-500">Supporting ads ({o.supporting_ad_ids.length})</p>
        <ul className="mt-1 flex flex-wrap gap-1">
          {ids.map((id) => (
            <li key={id}>
              {known(id) ? (
                <Link href={`/creative/?id=${encodeURIComponent(id)}`} className="rounded border border-slate-200 px-1.5 py-0.5 font-mono text-xs text-accent-700 hover:bg-accent-50">{id}</Link>
              ) : (
                <span className="rounded border border-dashed border-red-300 px-1.5 py-0.5 font-mono text-xs text-red-700" title="Not in the exported verified ads">{id}</span>
              )}
            </li>
          ))}
          {o.supporting_ad_ids.length > 12 ? (
            <li>
              <button type="button" onClick={() => setExpanded((e) => !e)} className="px-1.5 py-0.5 text-xs text-accent-700 hover:underline">
                {expanded ? "Show fewer" : `+${o.supporting_ad_ids.length - 12} more`}
              </button>
            </li>
          ) : null}
        </ul>
      </div>
    </li>
  );
}

function display(v: unknown): string {
  if (v === null || v === undefined) return "—";
  if (typeof v === "number") return Number.isInteger(v) ? String(v) : v.toFixed(3);
  if (typeof v === "string") return v;
  return JSON.stringify(v);
}
