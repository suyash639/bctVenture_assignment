"""
Generate the creative-quality markdown reports from the data files written by
scripts/build_validated_dataset.py (every number is computed, none hand-typed).

Writes:
  reports/creative_quality_audit.md
  reports/image_recovery_report.md
  reports/duplicate_analysis.md
  reports/dataset_validation_report.md
"""

from __future__ import annotations

import csv
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from config.settings import TARGET_BRANDS  # noqa: E402

Q = ROOT / "data" / "quality"
R = ROOT / "reports"
BRANDS = list(TARGET_BRANDS)


def rcsv(p):
    return list(csv.DictReader(open(p, encoding="utf-8"))) if Path(p).exists() else []


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join("" if v is None else str(v).replace("|", "/").replace("\n", " ") for v in r) + " |"
            for r in rows]
    return "\n".join(out)


def main():
    ds = rcsv(ROOT / "data/processed/validated_dataset.csv")
    av = rcsv(Q / "advertiser_verification.csv")
    iq = rcsv(Q / "image_quality_report.csv")
    rm = rcsv(Q / "recovery_manifest.csv")
    mp = rcsv(Q / "replacement_mapping.csv")
    dups = json.loads((Q / "duplicate_groups.json").read_text())["groups"]
    integ = json.loads((Q / "dataset_integrity_report.json").read_text())
    live = json.loads((Q / "live_cards.json").read_text())
    repl_cards = json.loads((Q / "replacement_cards.json").read_text()) if (Q / "replacement_cards.json").exists() else {}
    orig = [r for r in ds if r["record_origin"] == "original"]
    ver = [r for r in ds if r["final_status"] == "VERIFIED"]
    iq_repl = [r for r in iq if r["record_origin"] == "replacement"]
    per_brand = {b: sum(1 for r in ver if r["brand"] == b) for b in BRANDS}
    per_brand_static = {b: sum(1 for r in ver if r["brand"] == b and r["image_type"] == "static") for b in BRANDS}
    per_brand_repl = {b: sum(1 for r in ver if r["brand"] == b and r["record_origin"] == "replacement") for b in BRANDS}
    n_mismatch = sum(1 for r in av if r["advertiser_verification_status"] == "MISMATCH")
    n_unver = sum(1 for r in av if r["advertiser_verification_status"] == "UNVERIFIED")
    unresolved = [m for m in mp if m["status"] != "replaced"]
    sheets = sorted(p.name for p in (R / "creative_contact_sheets").glob("*.png"))

    # ------------------------------------------------------------ creative_quality_audit.md
    q_orig = Counter(r["image_quality_status"] for r in orig)
    q_repl = Counter(r["image_quality_status"] for r in iq_repl)
    lines = [
        "# Creative Quality Audit", "",
        "Generated by `scripts/generate_quality_reports.py` from `data/quality/*` and "
        "`data/processed/validated_dataset.csv`.", "",
        "## 1. Records checked", "",
        f"- Legacy dataset records checked against their live Ad Library card: **{len(av)}**",
        f"- Replacement candidates checked against their live card: **{len(repl_cards)}**", "",
        "## 2. Advertiser verification of the legacy IDs", "",
        table(["Result", "Count"], [
            ["Live card found", sum(1 for r in av if r["live_card_found"] == "True")],
            ["Advertiser belongs to the brand (VERIFIED)", sum(1 for r in av if r["advertiser_verification_status"] == "VERIFIED")],
            ["Advertiser is a different company (MISMATCH)", n_mismatch],
            ["Unverifiable (card not reachable)", n_unver]]), "",
        "Mismatched IDs (the ID itself belongs to another advertiser, so the record cannot be repaired, only replaced):", "",
        table(["Brand", "Ad ID", "Legacy page name", "Live advertiser"],
              [[r["dataset_brand"], r["ad_id"], r["legacy_page_name"], r["live_advertiser"]]
               for r in av if r["advertiser_verification_status"] == "MISMATCH"]), "",
        "Legacy metadata vs the live card for the same ID (brand-owned IDs only):", "",
        table(["Field", "match", "mismatch", "missing on one side", "both empty"],
              [[f.replace("legacy_vs_live_", "")] + [sum(1 for r in av if r["advertiser_verification_status"] == "VERIFIED"
                                                         and r.get(f) == k) for k in ("match", "mismatch", "missing_one", "both_empty")]
               for f in ("legacy_vs_live_page_name", "legacy_vs_live_start_date", "legacy_vs_live_cta",
                         "legacy_vs_live_landing_domain", "legacy_vs_live_copy")]), "",
        "Final records therefore take *all* metadata from the live card. Legacy values are kept in `legacy_*` columns.", "",
        "## 3. Images captured", "",
        f"- Legacy IDs whose own creative was recovered from the exact card: **{sum(1 for k, v in live.items() if v.get('asset_sha256'))}/{len(live)}**",
        f"- Replacement candidates with a recovered creative: **{sum(1 for v in repl_cards.values() if v.get('asset_sha256'))}/{len(repl_cards)}**",
        f"- Verified assets copied (byte-identical) to `data/creatives/verified/`: **{len(rm)}**", "",
        "## 4. Quality classification", "",
        "Thresholds: longest side ≥ 600 px; sharpness ≥ 100 (Laplacian variance at 600 px short side); "
        "contrast ≥ 0.05; plus a recorded visual review (`data/quality/visual_review.json`). "
        "VIDEO_ONLY = video poster that does not represent the full ad. UNVERIFIED = no asset could be checked.", "",
        table(["Status", "Legacy records", "Replacement candidates"],
              [[s, q_orig.get(s, 0), q_repl.get(s, 0)] for s in ("PASS", "REPLACE", "VIDEO_ONLY", "UNVERIFIED", "NEEDS_REVIEW")]), "",
        f"Of the {q_orig.get('REPLACE', 0)} legacy REPLACE records, "
        f"{sum(1 for r in orig if r['image_quality_status'] == 'REPLACE' and r['advertiser_verification_status'] != 'VERIFIED')} "
        "are other advertisers' ads (rejected on visual review as not a brand creative); the rest failed a "
        "quality threshold. These are listed below.", "",
        "Non-PASS legacy records with an asset:", "",
        table(["Brand", "Ad ID", "Status", "Reason"],
              [[r["brand"], r["ad_id"], r["image_quality_status"], r["exclusion_reasons"]] for r in orig
               if r["image_quality_status"] in ("REPLACE", "VIDEO_ONLY", "NEEDS_REVIEW")]), "",
        "## 5. Duplicates", "",
        f"- Duplicate groups: **{len(dups)}** ({sum(1 for g in dups if g['kind'] == 'exact')} exact-byte, "
        f"{sum(1 for g in dups if g['kind'] == 'near')} near-duplicate). Records excluded as duplicates: "
        f"**{sum(len(g['members']) - 1 for g in dups if not g.get('keep_all'))}**. See `reports/duplicate_analysis.md`.", "",
        "## 6. Final usable creatives per brand", "",
        table(["Brand", "VERIFIED", "of which static", "of which replacements", "Target"],
              [[b, per_brand[b], per_brand_static[b], per_brand_repl[b], 10] for b in BRANDS]
              + [["**Total**", sum(per_brand.values()), sum(per_brand_static.values()), sum(per_brand_repl.values()), 50]]), "",
        "## 7. Replacements", "",
        table(["Brand", "Original ad", "Original advertiser", "Why replaced", "Replacement ad", "Replacement advertiser"],
              [[m["brand"], m["original_ad_id"], m["original_advertiser"], m["failure_reason"],
                m["replacement_ad_id"] or "—", m["replacement_advertiser"] or "—"] for m in mp]), "",
        "## 8. Unresolved issues and access limitations", "",
        f"- Records still without a replacement: **{len(unresolved)}**"
        + (" (" + ", ".join(f"{m['brand']} {m['original_ad_id']}" for m in unresolved) + ")" if unresolved else "") + ".",
        "- These are marked `unavailable_for_visual_analysis` in `data/quality/replacement_mapping.csv`. No placeholder records were created.",
        "- Ad Library serves static creatives at a 600 px longest side. Higher-resolution originals are not "
        "publicly exposed, and nothing was upscaled.",
        "- Only the public, logged-out Ad Library was used. No login, CAPTCHA or rate-limit workaround was "
        "attempted. Advertiser websites and search engines were **not** used as creative sources, because "
        "an image found there cannot be tied to a specific Ad Library ID.", "",
        "## 9. Representative samples", "",
        "Brand contact sheets in `reports/creative_contact_sheets/` (labels: ad_id, quality status, duplicate status):", "",
    ] + [f"- [`{s}`](creative_contact_sheets/{s})" for s in sheets] + [""]
    (R / "creative_quality_audit.md").write_text("\n".join(lines))

    # ------------------------------------------------------------ image_recovery_report.md
    dims = Counter(r["original_dimensions"] for r in rm)
    meth = Counter(r["retrieval_method"] for r in rm)
    lines = [
        "# Image Recovery Report", "",
        "## Method", "",
        "1. Open the public single-ad Ad Library URL with full query parameters "
        "(`?active_status=all&ad_type=all&country=IN&id=<ad_id>&media_type=all`). "
        "The legacy pipeline used the bare `?id=<ad_id>` form, which opens a generic results page "
        "rather than the ad. That is the root cause of the legacy image/ID mismatches.",
        "2. Find the card whose text is exactly `Library ID: <ad_id>`, then climb to the largest "
        "ancestor that contains only that one Library ID.",
        "3. Take that card's own creative: the first `<img>` ≥ 200 px (static / carousel first frame) or "
        "the `<video>` poster.",
        "4. Download the asset bytes as served, in the same browser session. No screenshot, crop, "
        "re-encode or upscale is applied, so original and final dimensions are identical.",
        "5. Record source URL, method, dimensions, SHA-256 and timestamp (`data/quality/recovery_manifest.csv`).", "",
        "Implementation: `scripts/verify_creatives.py` (2 concurrent browser workers; stops if a login wall appears).", "",
        "## Results", "",
        f"- Legacy IDs: {sum(1 for v in live.values() if v.get('found'))}/{len(live)} cards found, "
        f"{sum(1 for v in live.values() if v.get('asset_sha256'))}/{len(live)} assets recovered.",
        f"- Replacement candidates: {sum(1 for v in repl_cards.values() if v.get('found'))}/{len(repl_cards)} cards found, "
        f"{sum(1 for v in repl_cards.values() if v.get('asset_sha256'))}/{len(repl_cards)} assets recovered.",
        f"- Verified assets saved to `data/creatives/verified/<brand>/<ad_id>.<ext>`: {len(rm)}", "",
        table(["Retrieval method", "Assets"], sorted(meth.items())), "",
        table(["Original = final dimensions", "Assets"], sorted(dims.items(), key=lambda x: -x[1])), "",
        "## Strategies considered", "",
        table(["Strategy", "Used?", "Why"], [
            ["Public single-ad Ad Library page", "Yes (primary)", "Only source that ties an image to an exact Library ID and advertiser."],
            ["Advertiser's own Ad Library page listing (`view_all_page_id`)", "Yes (replacement discovery)", "Finds more same-brand ads; each one is then re-verified on its single-ad card."],
            ["Assets linked from the verified card (img src / video poster)", "Yes", "The card's own CDN asset, fetched in-session."],
            ["Advertiser websites / landing pages / campaign pages", "No", "Their images are product or catalogue assets that cannot be proven to be the creative of a given ad ID."],
            ["Search-engine images", "No", "Unverifiable provenance."]]), "",
        "## Failures", "",
        table(["Ad ID", "Problem"],
              [[k, v.get("error") or v.get("download_error") or ("login wall" if v.get("login_wall") else "card not found")]
               for k, v in {**live, **repl_cards}.items() if not v.get("asset_sha256")]) or "None.", "",
    ]
    (R / "image_recovery_report.md").write_text("\n".join(lines))

    # ------------------------------------------------------------ duplicate_analysis.md
    by_id = {r["ad_id"]: r for r in iq}
    lines = ["# Duplicate Analysis", "",
             "- Exact duplicates: identical SHA-256 of the downloaded bytes.",
             "- Near duplicates: 64-bit difference hash (dHash) with Hamming distance ≤ 6, grouped by union-find.",
             "- Card evidence: Meta's own \"N ads use this creative and text\" counter (`n_ads_same_creative`).",
             "- Policy: one representative per group enters the final dataset. Others are kept in the "
             "dataset as `DUPLICATE_OF:<id>` with `final_status = EXCLUDED`. Identical creatives run under "
             "different ad IDs would otherwise over-weight one creative in clustering.", "",
             f"Groups found: **{len(dups)}**.", ""]
    for g in dups:
        lines += [f"### {g['group_id']} — {g['kind']} ({', '.join(g['brands'])})", "",
                  table(["Ad ID", "Origin", "Duplicate status", "Sharpness", "Card: ads using creative"],
                        [[m, by_id.get(m, {}).get("record_origin"), by_id.get(m, {}).get("duplicate_status"),
                          by_id.get(m, {}).get("sharpness"),
                          (live.get(m) or repl_cards.get(m) or {}).get("n_ads_same_creative")] for m in g["members"]]),
                  "", f"Representative kept: `{g['representative']}`. Decision: {g['decision']}.", ""]
    (R / "duplicate_analysis.md").write_text("\n".join(lines))

    # ------------------------------------------------------------ dataset_validation_report.md
    lines = [
        "# Dataset Validation Report", "",
        "Outputs: `data/processed/validated_dataset.csv` / `.json` (raw and legacy files untouched).", "",
        "## Acceptance rules", "",
        "A record is `final_status = VERIFIED` only if all of these hold:", "",
        "1. `advertiser_verification_status = VERIFIED`: the live card's advertiser belongs to the brand "
        "(brand page, sub-brand page, or a partnership ad naming the brand).",
        "2. `image_verification_status = VERIFIED`: the asset was downloaded from that exact card.",
        "3. `metadata_verification_status = VERIFIED`: metadata comes from the same card, and the start date is present.",
        "4. `image_quality_status = PASS`: objective thresholds are met and a recorded visual review passed it.",
        "5. `duplicate_status` ∈ {UNIQUE, GROUP_REPRESENTATIVE}.", "",
        "## Counts", "",
        f"- Rows in validated dataset: **{len(ds)}** (all {len(orig)} legacy records for traceability + "
        f"{sum(1 for r in ds if r['record_origin'] == 'replacement')} selected replacements)",
        f"- **VERIFIED: {len(ver)}** · EXCLUDED: {len(ds) - len(ver)}", "",
        table(["Brand", "VERIFIED", "static", "video poster", "originals retained", "replacements"],
              [[b, per_brand[b], per_brand_static[b], per_brand[b] - per_brand_static[b],
                per_brand[b] - per_brand_repl[b], per_brand_repl[b]] for b in BRANDS]), "",
        "Exclusion reasons (legacy records):", "",
        table(["Reason (first)", "Records"], Counter(
            (r["exclusion_reasons"].split(";")[0].split("(")[0].strip() or "—")
            for r in orig if r["final_status"] != "VERIFIED").most_common()), "",
        "## Integrity checks (`data/quality/dataset_integrity_report.json`)", "",
        table(["Check", "Result", "Detail"],
              [[c["check"], "PASS" if c["passed"] else "**FAIL**", c["detail"] or ""] for c in integ["checks"]]), "",
        f"Overall: **{'PASSED' if integ['passed'] else 'FAILED'}**.", "",
        "Optional fields missing on VERIFIED records (left empty as unavailable on the card, never inferred): "
        + ", ".join(f"{k}: {v}" for k, v in integ["verified_records_missing_optional_fields"].items()) + ".", "",
        "## Advertiser types among VERIFIED records", "",
        table(["Type", "Records"], Counter(r["advertiser_type"] for r in ver).most_common()), "",
    ]
    (R / "dataset_validation_report.md").write_text("\n".join(lines))
    print("reports written:", [p for p in ("creative_quality_audit.md", "image_recovery_report.md",
                                           "duplicate_analysis.md", "dataset_validation_report.md")])


if __name__ == "__main__":
    main()
